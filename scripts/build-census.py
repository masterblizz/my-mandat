#!/usr/bin/env python3
"""Build app/data/seatCensus.ts from DOSM's 2020 census by constituency.

Source: dosm-malaysia/data-open (licence CC BY 4.0),
  datasets/census/census_parlimen.csv and census_dun.csv
Usage:  python3 scripts/build-census.py <path to data-open/datasets/census>
"""
import csv, sys, os

STATE_ID = {
    "Johor": "johor", "Kedah": "kedah", "Kelantan": "kelantan", "Melaka": "melaka",
    "Negeri Sembilan": "ns", "Pahang": "pahang", "Perak": "perak", "Perlis": "perlis",
    "Pulau Pinang": "penang", "Sabah": "sabah", "Sarawak": "sarawak", "Selangor": "selangor",
    "Terengganu": "terengganu", "W.P. Kuala Lumpur": "wp", "W.P. Labuan": "wp", "W.P. Putrajaya": "wp",
}

def rows(path):
    with open(path, encoding="utf-8-sig") as f:
        return list(csv.DictReader(f))

def num(v):
    return float(str(v).replace(",", "") or 0)

def entry(r, name_key):
    name = r[name_key].split(" ", 1)[1]
    return int(num(r["population_total"])), int(num(r["household_total"])), round(num(r["area_km2"]), 1), name

src = sys.argv[1]
par = rows(os.path.join(src, "census_parlimen.csv"))
dun = rows(os.path.join(src, "census_dun.csv"))
out = [
    "// Real population, households and area per constituency (DOSM Population",
    "// and Housing Census 2020, open data, CC BY 4.0 — dosm-malaysia/data-open,",
    "// datasets/census). Generated by scripts/build-census.py; do not edit.",
    "// Keys: parliament by official code (\"P.083\"); state seats by state id and",
    "// code (\"pahang:N.12\"). Values: [population, households, area km², name, state].",
    "",
    "export type CensusRow = readonly [population: number, households: number, areaKm2: number, name: string, state: string];",
    "",
    "export const PARLIMEN_CENSUS: Record<string, CensusRow> = {",
]
for r in par:
    p, h, a, n = entry(r, "parlimen")
    out.append(f'  "{r["code_parlimen"]}": [{p}, {h}, {a}, {n!r}, {STATE_ID[r["state"]]!r}],'.replace("'", '"'))
out += ["};", "", "export const DUN_CENSUS: Record<string, CensusRow> = {"]
for r in dun:
    p, h, a, n = entry(r, "dun")
    out.append(f'  "{STATE_ID[r["state"]]}:{r["code_dun"]}": [{p}, {h}, {a}, {n!r}, {STATE_ID[r["state"]]!r}],'.replace("'", '"'))
out += ["};", ""]
open("app/data/seatCensus.ts", "w").write("\n".join(out))
print(len(par), "parliament,", len(dun), "state seats")
