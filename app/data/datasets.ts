export type DatasetKind = "dummy" | "real-malaysia";

export interface DatasetParty {
  id: string;
  name: string;
  abbreviation: string;
  coalition?: string;
  color: string;
  ideology: string;
  leader: string;
  founded?: number;
  nationalSupport: number;
  projectedSeats: number;
}

export interface DatasetPolitician {
  id: string;
  name: string;
  partyId: string;
  party: string;
  role: string;
  state?: string;
  constituency?: string;
  influence: number;
  charisma: number;
  credibility: number;
  negotiation: number;
  strategy: number;
}

export interface DatasetStateProjection {
  stateId: string;
  stateName: string;
  leadingPartyId: string;
  leadingParty: string;
  support: number;
  projectedSeats: number;
  status: "safe" | "lean" | "contested" | "risk";
}

export interface GameDataset {
  id: DatasetKind;
  label: string;
  description: string;
  dataNote: string;
  parties: DatasetParty[];
  politicians: DatasetPolitician[];
  stateProjections: DatasetStateProjection[];
}

