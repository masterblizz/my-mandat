declare v_world record;
begin
  for v_world in select id from public.worlds w where w.lifecycle_status <> 'archived' and not exists (select 1 from public.world_elections e where e.world_id = w.id) loop
    perform public.open_world_election(v_world.id, 1, now());
  end loop;
end $$;
