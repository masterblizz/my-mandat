-- Count every seat, then form the government. Called once per election, under the world lock.
create or replace function public.resolve_world_election(p_election_id uuid)
returns jsonb language plpgsql security definer set search_path = public as $$
declare
  v_election public.world_elections; v_world public.worlds; v_seat record; v_cand record;
  v_turnout double precision; v_total_weight double precision; v_cast integer; v_count integer;
  v_seat_total integer; v_won integer := 0; v_gov record; v_opp record; v_head uuid; v_opp_head uuid; v_summary jsonb;
begin
  select * into v_election from public.world_elections where id = p_election_id for update;
  if not found then raise exception 'election_not_found'; end if;
  if v_election.status = 'complete' then return v_election.summary; end if;
  select * into v_world from public.worlds where id = v_election.world_id;

  for v_seat in
    select s.constituency_id, s.voters from public.world_region_seats s where s.region_id = v_world.region_id
    union all
    -- Worlds without a region: count only seats that actually have candidates.
    select distinct c.constituency_id, 60000 from public.world_candidacies c where v_world.region_id is null and c.election_id = p_election_id and c.status = 'standing'
  loop
    select count(*) into v_count from public.world_candidacies where election_id = p_election_id and constituency_id = v_seat.constituency_id and status = 'standing';
    continue when v_count = 0;
    v_turnout := 0.62 + public.seeded_unit(p_election_id::text || v_seat.constituency_id || 'turnout') * 0.16;
    v_cast := round(v_seat.voters * v_turnout);

    -- Strength = 10 + campaign score + up to +15 from world reputation; weights get ±12% local noise.
    create temporary table if not exists pg_temp.seat_weights (candidacy_id uuid, character_id uuid, party_id uuid, campaign_score integer, created_at timestamptz, weight double precision) on commit drop;
    truncate pg_temp.seat_weights;
    insert into pg_temp.seat_weights
    select c.id, c.character_id, c.party_id, c.campaign_score, c.created_at,
      power(greatest(1, 10 + c.campaign_score + least(15, coalesce(r.reputation, 0) / 10.0)), 1.6)
        * (0.88 + public.seeded_unit(p_election_id::text || c.id::text) * 0.24)
    from public.world_candidacies c
    left join public.world_account_reputation r on r.world_id = c.world_id and r.account_id = c.account_id
    where c.election_id = p_election_id and c.constituency_id = v_seat.constituency_id and c.status = 'standing';
    select sum(weight) into v_total_weight from pg_temp.seat_weights;

    insert into public.world_election_results(election_id, world_id, constituency_id, candidacy_id, character_id, party_id, votes, vote_share, is_winner, unopposed)
    select p_election_id, v_world.id, v_seat.constituency_id, w.candidacy_id, w.character_id, w.party_id,
      round(v_cast * w.weight / v_total_weight), round((100 * w.weight / v_total_weight)::numeric, 2),
      row_number() over (order by w.weight desc, w.campaign_score desc, w.created_at) = 1,
      v_count = 1
    from pg_temp.seat_weights w
    on conflict (election_id, candidacy_id) do nothing;
    v_won := v_won + 1;
  end loop;

  -- Blocs: an active coalition (2+ parties) or a lone party; independents are their own bloc.
  create temporary table if not exists pg_temp.bloc_results (bloc_key text, bloc_name text, seats integer, votes bigint) on commit drop;
  truncate pg_temp.bloc_results;
  insert into pg_temp.bloc_results
  select bloc_key, min(bloc_name), count(*) filter (where is_winner), sum(votes)
  from (
    select r.is_winner, r.votes,
      coalesce('c:' || co.id::text, 'p:' || p.id::text, 'i:' || r.candidacy_id::text) as bloc_key,
      coalesce(co.name, p.abbreviation, 'BEBAS') as bloc_name
    from public.world_election_results r
    left join public.world_parties p on p.id = r.party_id
    left join lateral (
      select c.id, c.name from public.world_coalition_parties cp join public.world_coalitions c on c.id = cp.coalition_id
      where cp.party_id = r.party_id and c.status = 'active' order by cp.joined_at limit 1
    ) co on true
    where r.election_id = p_election_id
  ) x group by bloc_key;

  v_seat_total := coalesce((select seat_count from public.world_regions where id = v_world.region_id), v_won);
  select * into v_gov from pg_temp.bloc_results where seats > 0 order by seats desc, votes desc limit 1;
  select * into v_opp from pg_temp.bloc_results where seats > 0 and bloc_key <> coalesce(v_gov.bloc_key, '') order by seats desc, votes desc limit 1;

  -- Leader of a bloc: the elected founder of its largest party if any, otherwise its top vote-getter.
  if v_gov.bloc_key is not null then
    select r.character_id into v_head from public.world_election_results r
    join public.world_candidacies c on c.id = r.candidacy_id
    left join public.world_parties p on p.id = r.party_id
    where r.election_id = p_election_id and r.is_winner
      and coalesce((select 'c:' || cp.coalition_id::text from public.world_coalition_parties cp join public.world_coalitions co on co.id = cp.coalition_id where cp.party_id = r.party_id and co.status = 'active' order by cp.joined_at limit 1), 'p:' || r.party_id::text, 'i:' || r.candidacy_id::text) = v_gov.bloc_key
    order by (p.created_by = c.account_id) desc nulls last,
      (select count(*) from public.world_election_results r2 where r2.election_id = p_election_id and r2.is_winner and r2.party_id = r.party_id) desc,
      r.votes desc
    limit 1;
  end if;
  if v_opp.bloc_key is not null then
    select r.character_id into v_opp_head from public.world_election_results r
    join public.world_candidacies c on c.id = r.candidacy_id
    left join public.world_parties p on p.id = r.party_id
    where r.election_id = p_election_id and r.is_winner
      and coalesce((select 'c:' || cp.coalition_id::text from public.world_coalition_parties cp join public.world_coalitions co on co.id = cp.coalition_id where cp.party_id = r.party_id and co.status = 'active' order by cp.joined_at limit 1), 'p:' || r.party_id::text, 'i:' || r.candidacy_id::text) = v_opp.bloc_key
    order by (p.created_by = c.account_id) desc nulls last,
      (select count(*) from public.world_election_results r2 where r2.election_id = p_election_id and r2.is_winner and r2.party_id = r.party_id) desc,
      r.votes desc
    limit 1;
  end if;

  update public.world_political_offices set status = 'ended' where world_id = v_world.id and status = 'appointed';
  if v_head is not null then
    insert into public.world_political_offices(world_id, office_key, holder_character_id, status, term_number)
    values (v_world.id, 'head_of_government', v_head, 'appointed', v_election.cycle_number)
    on conflict (world_id, office_key, term_number) do update set holder_character_id = excluded.holder_character_id, status = 'appointed';
  end if;
  if v_opp_head is not null then
    insert into public.world_political_offices(world_id, office_key, holder_character_id, status, term_number)
    values (v_world.id, 'opposition_leader', v_opp_head, 'appointed', v_election.cycle_number)
    on conflict (world_id, office_key, term_number) do update set holder_character_id = excluded.holder_character_id, status = 'appointed';
  end if;

  v_summary := jsonb_build_object(
    'seat_total', v_seat_total,
    'seats_contested', v_won,
    'majority_needed', v_seat_total / 2 + 1,
    'government', case when v_gov.bloc_key is null then null else jsonb_build_object('bloc', v_gov.bloc_name, 'seats', v_gov.seats, 'majority', v_gov.seats > v_seat_total / 2, 'head_character_id', v_head) end,
    'opposition', case when v_opp.bloc_key is null then null else jsonb_build_object('bloc', v_opp.bloc_name, 'seats', v_opp.seats, 'head_character_id', v_opp_head) end,
    'blocs', coalesce((select jsonb_agg(jsonb_build_object('bloc', bloc_name, 'seats', seats, 'votes', votes) order by seats desc, votes desc) from pg_temp.bloc_results), '[]'::jsonb)
  );
  update public.world_elections set status = 'complete', resolved_at = now(), summary = v_summary where id = p_election_id;
  return v_summary;
end; $$;
revoke all on function public.resolve_world_election(uuid) from public, anon, authenticated;

-- Moves a world's election through its phases according to the clock. Idempotent;
-- safe for any member (or the scheduler) to call as often as they like.
create or replace function public.advance_world_election(p_world_id uuid)
returns public.world_elections language plpgsql security definer set search_path = public as $$
declare v_election public.world_elections; v_guard integer := 0;
begin
  if coalesce(auth.jwt() ->> 'role', '') <> 'service_role' and not public.is_active_world_member(p_world_id) then raise exception 'world_access_denied'; end if;
  perform 1 from public.worlds where id = p_world_id for update;
  if not found then raise exception 'world_not_available'; end if;
  select * into v_election from public.world_elections where world_id = p_world_id order by cycle_number desc limit 1;
  if not found then
    v_election := public.open_world_election(p_world_id, 1, now());
  end if;
  loop
    v_guard := v_guard + 1; exit when v_guard > 8;
    if v_election.status = 'nomination' and now() >= v_election.campaign_opens_at then
      update public.world_elections set status = 'campaign' where id = v_election.id returning * into v_election;
    elsif v_election.status = 'campaign' and now() >= v_election.polling_opens_at then
      update public.world_elections set status = 'polling' where id = v_election.id returning * into v_election;
    elsif v_election.status = 'polling' and now() >= v_election.results_at then
      perform public.resolve_world_election(v_election.id);
      -- The next cycle starts at the scheduled time, or now if the world sat idle past it.
      v_election := public.open_world_election(p_world_id, v_election.cycle_number + 1, greatest(v_election.results_at, now() - interval '1 minute'));
    else
      exit;
    end if;
  end loop;
  return v_election;
end; $$;
revoke all on function public.advance_world_election(uuid) from public, anon;
grant execute on function public.advance_world_election(uuid) to authenticated, service_role;

-- Stand in a seat during nomination. Party members stand for their party; others stand as independents.
create or replace function public.stand_for_world_election(p_world_id uuid, p_character_id uuid, p_constituency_id text)
returns public.world_candidacies language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_election public.world_elections; v_party uuid; v_row public.world_candidacies;
begin
  v_election := public.advance_world_election(p_world_id);
  if v_election.status <> 'nomination' then raise exception 'nomination_closed'; end if;
  if not exists (select 1 from public.characters where id = p_character_id and world_id = p_world_id and account_id = v_user and lifecycle_status = 'active') then raise exception 'character_access_denied'; end if;
  if not public.is_world_seat(p_world_id, p_constituency_id) then raise exception 'invalid_home_constituency'; end if;
  if exists (select 1 from public.world_candidacies where election_id = v_election.id and account_id = v_user and status = 'standing') then raise exception 'already_standing'; end if;
  select party_id into v_party from public.world_party_memberships where world_id = p_world_id and account_id = v_user and status = 'active';
  if v_party is not null and exists (select 1 from public.world_candidacies where election_id = v_election.id and constituency_id = p_constituency_id and party_id = v_party and status = 'standing') then raise exception 'party_seat_taken'; end if;
  insert into public.world_candidacies(election_id, world_id, constituency_id, character_id, account_id, party_id)
  values (v_election.id, p_world_id, p_constituency_id, p_character_id, v_user, v_party) returning * into v_row;
  return v_row;
end; $$;
revoke all on function public.stand_for_world_election(uuid, uuid, text) from public, anon;
grant execute on function public.stand_for_world_election(uuid, uuid, text) to authenticated;

-- Withdraw during nomination: the candidate themself, or a founder/officer of the candidate's party.
create or replace function public.withdraw_world_candidacy(p_candidacy_id uuid)
returns public.world_candidacies language plpgsql security definer set search_path = public as $$
declare v_user uuid := auth.uid(); v_row public.world_candidacies; v_election public.world_elections;
begin
  select * into v_row from public.world_candidacies where id = p_candidacy_id;
  if not found then raise exception 'candidacy_not_found'; end if;
  v_election := public.advance_world_election(v_row.world_id);
  if v_election.id <> v_row.election_id or v_election.status <> 'nomination' then raise exception 'nomination_closed'; end if;
  if v_row.account_id <> v_user and not exists (
    select 1 from public.world_party_memberships where party_id = v_row.party_id and account_id = v_user and status = 'active' and role in ('founder', 'officer')
  ) then raise exception 'party_permission_denied'; end if;
  update public.world_candidacies set status = 'withdrawn' where id = p_candidacy_id and status = 'standing' returning * into v_row;
  return v_row;
end; $$;
revoke all on function public.withdraw_world_candidacy(uuid) from public, anon;
grant execute on function public.withdraw_world_candidacy(uuid) to authenticated;

-- One campaign action. Two per candidate per campaign day.
--   walkabout  +4
--   rally      +2…+8 (crowd turnout varies)
--   attack     a rival in the same seat: rival −3 and you +1, but 30% of the time it backfires (you −2)
create or replace function public.take_world_campaign_action(p_candidacy_id uuid, p_action_type text, p_target_candidacy_id uuid default null)
returns public.world_campaign_actions language plpgsql security definer set search_path = public as $$
declare
  v_user uuid := auth.uid(); v_row public.world_candidacies; v_target public.world_candidacies; v_election public.world_elections;
  v_day integer; v_roll double precision; v_self integer; v_other integer := 0; v_backfired boolean := false; v_action public.world_campaign_actions;
begin
  select * into v_row from public.world_candidacies where id = p_candidacy_id for update;
  if not found or v_row.account_id <> v_user or v_row.status <> 'standing' then raise exception 'character_access_denied'; end if;
  v_election := public.advance_world_election(v_row.world_id);
  if v_election.id <> v_row.election_id or v_election.status <> 'campaign' then raise exception 'campaign_closed'; end if;
  v_day := least(5, greatest(1, floor(extract(epoch from (now() - v_election.campaign_opens_at)) / 86400)::integer + 1));
  if (select count(*) from public.world_campaign_actions where candidacy_id = p_candidacy_id and campaign_day = v_day) >= 2 then raise exception 'campaign_action_limit'; end if;
  v_roll := public.seeded_unit(p_candidacy_id::text || v_day || (select count(*) from public.world_campaign_actions where candidacy_id = p_candidacy_id) || clock_timestamp()::text);
  if p_action_type = 'walkabout' then
    v_self := 4;
  elsif p_action_type = 'rally' then
    v_self := 2 + floor(v_roll * 7)::integer;
  elsif p_action_type = 'attack' then
    select * into v_target from public.world_candidacies where id = p_target_candidacy_id for update;
    if not found or v_target.election_id <> v_row.election_id or v_target.constituency_id <> v_row.constituency_id or v_target.id = v_row.id or v_target.status <> 'standing' then raise exception 'invalid_campaign_target'; end if;
    if v_roll < 0.3 then v_self := -2; v_backfired := true; else v_self := 1; v_other := -3; end if;
  else
    raise exception 'invalid_campaign_action';
  end if;
  update public.world_candidacies set campaign_score = greatest(-10, campaign_score + v_self) where id = v_row.id;
  if v_other <> 0 then update public.world_candidacies set campaign_score = greatest(-10, campaign_score + v_other) where id = v_target.id; end if;
  insert into public.world_campaign_actions(election_id, world_id, candidacy_id, account_id, action_type, target_candidacy_id, campaign_day, self_delta, target_delta, backfired)
  values (v_row.election_id, v_row.world_id, v_row.id, v_user, p_action_type, p_target_candidacy_id, v_day, v_self, v_other, v_backfired)
  returning * into v_action;
  return v_action;
end; $$;
revoke all on function public.take_world_campaign_action(uuid, text, uuid) from public, anon;
grant execute on function public.take_world_campaign_action(uuid, text, uuid) to authenticated;

