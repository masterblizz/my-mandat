where w.is_system and w.region_id is null and w.system_number is not null;
update public.worlds w set name = r.name_ms || ' ' || (
    select count(*) from public.worlds o where o.is_system and o.region_id = w.region_id and o.system_number <= w.system_number)
from public.world_regions r
