-- Deterministic 0..1 value from a text seed, so a resolution is reproducible.
create or replace function public.seeded_unit(p_seed text)
returns double precision language sql immutable as $$
  select ('x' || substr(md5(p_seed), 1, 8))::bit(32)::bigint / 4294967295.0;
$$;

-- Cycle shape (hours from the cycle start). 24h nomination, 5×24h campaign, 24h polling.
