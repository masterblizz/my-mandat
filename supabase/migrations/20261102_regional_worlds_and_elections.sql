-- Regional worlds + player-vs-player elections.
--
-- * Every system world covers ONE region (Kuala Lumpur, Pulau Pinang,
--   Selangor, …) instead of all of Malaysia, so 100 players share 6–31
--   parliamentary seats and routinely contest against each other.
--   New worlds rotate through the regions in world_regions.rotation_order.
-- * Each world runs a repeating 7-day election cycle:
--     day 1      nomination  – players stand in one seat (under their party,
--                              or as an independent if they have none)
--     days 2–6   campaign    – candidates spend 2 campaign actions per day
--     day 7      polling     – no campaigning; results at the end of the day
--   Results are computed server-side from campaign effort only (simulated
--   electorate), then the largest party/coalition bloc forms the government.
-- * Phases advance lazily: advance_world_election() is idempotent and is
--   called whenever a member opens the election page and by the scheduler.
-- Forward-only and idempotent. Run after 20261101.

-- ───────────────────────── regions ─────────────────────────
create table if not exists public.world_regions (
  id text primary key,
  name_ms text not null,
  name_en text not null,
  head_title_ms text not null,
  head_title_en text not null,
  rotation_order integer not null unique,
  seat_count integer not null check (seat_count > 0)
);
create table if not exists public.world_region_seats (
  constituency_id text primary key,
  region_id text not null references public.world_regions(id) on delete cascade,
  code text not null,
  name text not null,
  voters integer not null check (voters > 0),
  seat_order integer not null,
  unique (region_id, seat_order)
);
alter table public.world_regions enable row level security;
alter table public.world_region_seats enable row level security;
drop policy if exists "regions: signed-in read" on public.world_regions;
create policy "regions: signed-in read" on public.world_regions for select to authenticated using (true);
drop policy if exists "region seats: signed-in read" on public.world_region_seats;
create policy "region seats: signed-in read" on public.world_region_seats for select to authenticated using (true);
grant select on public.world_regions, public.world_region_seats to authenticated;

